
import json
from pathlib import Path
from typing import Any

from web3 import Web3
from web3.contract import Contract

from app.core.config import settings


class BlockchainConnectionError(Exception):
    """Raised when the blockchain connection or configuration is invalid."""


class BlockchainService:
    """
    Read-only connection service for the Voting smart contract.

    Responsibilities:
    - Connect to the configured Ethereum JSON-RPC endpoint.
    - Validate the connected chain ID.
    - Load deployment addresses and the compiled contract ABI.
    - Verify that Voting and Semaphore bytecode exist on-chain.
    - Initialize the Voting contract interface.
    """

    def __init__(self) -> None:
        self.w3 = Web3(
            Web3.HTTPProvider(
                settings.blockchain_rpc_url,
                request_kwargs={"timeout": 10},
            )
        )

        self.chain_id: int | None = None
        self.voting_address: str | None = None
        self.semaphore_address: str | None = None
        self.voting_contract: Contract | None = None

    def connect(self) -> None:
        """Connect to the RPC endpoint and initialize the Voting contract."""

        if not self.w3.is_connected():
            raise BlockchainConnectionError(
                "Unable to connect to the configured blockchain RPC endpoint."
            )

        self.chain_id = self.w3.eth.chain_id

        if self.chain_id != settings.expected_chain_id:
            raise BlockchainConnectionError(
                f"Chain ID mismatch. Expected "
                f"{settings.expected_chain_id}, received {self.chain_id}."
            )

        deployment = self._load_deployment()
        contracts = deployment.get("contracts")

        if not isinstance(contracts, dict):
            raise BlockchainConnectionError(
                "Deployment file does not contain a valid contracts object."
            )

        self.voting_address = self._validate_address(
            contracts.get("voting"),
            "Voting",
        )

        self.semaphore_address = self._validate_address(
            contracts.get("semaphore"),
            "Semaphore",
        )

        artifact = self._load_voting_artifact()
        abi = artifact.get("abi")

        if not isinstance(abi, list) or not abi:
            raise BlockchainConnectionError(
                "Voting artifact does not contain a valid ABI."
            )

        self._verify_contract_bytecode(
            self.voting_address,
            "Voting",
        )

        self._verify_contract_bytecode(
            self.semaphore_address,
            "Semaphore",
        )

        self.voting_contract = self.w3.eth.contract(
            address=self.voting_address,
            abi=abi,
        )

    def _verify_contract_bytecode(
        self,
        address: str,
        contract_name: str,
    ) -> None:
        """Verify that a deployed contract has bytecode at its address."""

        bytecode = self.w3.eth.get_code(address)

        if not bytecode:
            raise BlockchainConnectionError(
                f"No contract bytecode found at the configured "
                f"{contract_name} address."
            )

    def _load_deployment(self) -> dict[str, Any]:
        """Load and validate the local deployment JSON file."""

        deployment_path = settings.deployment_path

        if not deployment_path.is_file():
            raise BlockchainConnectionError(
                f"Deployment file not found: {deployment_path}"
            )

        try:
            with deployment_path.open("r", encoding="utf-8") as file:
                deployment = json.load(file)

        except (OSError, json.JSONDecodeError) as exc:
            raise BlockchainConnectionError(
                f"Unable to read deployment file: {exc}"
            ) from exc

        if not isinstance(deployment, dict):
            raise BlockchainConnectionError(
                "Deployment file must contain a JSON object."
            )

        if deployment.get("network") != "localhost":
            raise BlockchainConnectionError(
                "The configured deployment is not for localhost."
            )

        try:
            deployment_chain_id = int(deployment.get("chainId", 0))
        except (TypeError, ValueError) as exc:
            raise BlockchainConnectionError(
                "Deployment file contains an invalid chain ID."
            ) from exc

        if deployment_chain_id != settings.expected_chain_id:
            raise BlockchainConnectionError(
                "Deployment chain ID does not match the expected chain ID."
            )

        return deployment

    def _load_voting_artifact(self) -> dict[str, Any]:
        """Load the compiled Voting contract artifact generated by Hardhat."""

        project_root = settings.deployment_path.parent.parent

        artifact_path = (
            project_root
            / "artifacts"
            / "contracts"
            / "Voting.sol"
            / "Voting.json"
        )

        if not artifact_path.is_file():
            raise BlockchainConnectionError(
                f"Voting contract artifact not found: {artifact_path}"
            )

        try:
            with artifact_path.open("r", encoding="utf-8") as file:
                artifact = json.load(file)

        except (OSError, json.JSONDecodeError) as exc:
            raise BlockchainConnectionError(
                f"Unable to read Voting artifact: {exc}"
            ) from exc

        if not isinstance(artifact, dict):
            raise BlockchainConnectionError(
                "Voting artifact must contain a JSON object."
            )

        return artifact

    def _validate_address(
        self,
        address: Any,
        contract_name: str,
    ) -> str:
        """Validate and normalize an Ethereum contract address."""

        if not isinstance(address, str) or not Web3.is_address(address):
            raise BlockchainConnectionError(
                f"Invalid {contract_name} contract address in deployment file."
            )

        return Web3.to_checksum_address(address)

    def get_voting_contract(self) -> Contract:
        """Return the initialized Voting contract interface."""

        if self.voting_contract is None:
            raise BlockchainConnectionError(
                "Voting contract is not initialized. Call connect() first."
            )

        return self.voting_contract


# Shared service instance for the FastAPI application.
blockchain_service = BlockchainService()
